"""Inline ui/app.js into the Desktop module and the dashboard bundle (neither host compiles JSX or imports)."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent
BANNER = "// Generated by build.py from ui/; edit those files instead.\n"


def build() -> None:
    app = (ROOT / "ui" / "app.js").read_text().rstrip() + "\n"
    for template, target in (("desktop.js", "desktop/plugin.js"), ("dashboard.js", "dashboard/dist/index.js")):
        source = (ROOT / "ui" / template).read_text()
        indent = "  " if template == "dashboard.js" else ""
        inlined = "".join(indent + line if line.strip() else line for line in app.splitlines(keepends=True))
        output = ROOT / target
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(BANNER + source.replace(f"{indent}/* @app */\n", inlined))
    (ROOT / "dashboard" / "dist" / "style.css").write_text("/* Usage Gate styles are inline and follow the host theme. */\n")


if __name__ == "__main__":
    build()
